async fn workspace_onay_mock_drift_before_answer(
    target: PathBuf,
    changed: String,
) -> (String, tokio::task::JoinHandle<Vec<Value>>) {
    use tokio::io::{AsyncReadExt, AsyncWriteExt};
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let url = format!("http://{}/api/chat", listener.local_addr().unwrap());
    let server = tokio::spawn(async move {
        tokio::time::timeout(std::time::Duration::from_secs(10), async move {
            let mut requests = Vec::new();
            for (step, reply) in [
                workspace_onay_tool("verify_workspace", json!({"changes": workspace_onay_plan()})),
                workspace_onay_plain(),
            ].into_iter().enumerate() {
                let (mut socket, _) = listener.accept().await.unwrap();
                let mut bytes = Vec::new();
                let (body_start, content_len) = loop {
                    let mut chunk = [0; 4096];
                    let count = socket.read(&mut chunk).await.unwrap();
                    assert!(count > 0);
                    bytes.extend_from_slice(&chunk[..count]);
                    if let Some(end) = bytes.windows(4).position(|window| window == b"\r\n\r\n") {
                        let headers = std::str::from_utf8(&bytes[..end]).unwrap();
                        let len = headers.lines().filter_map(|line| line.split_once(':'))
                            .find(|(name, _)| name.eq_ignore_ascii_case("content-length"))
                            .unwrap().1.trim().parse::<usize>().unwrap();
                        break (end + 4, len);
                    }
                };
                while bytes.len() < body_start + content_len {
                    let mut chunk = [0; 4096];
                    let count = socket.read(&mut chunk).await.unwrap();
                    assert!(count > 0);
                    bytes.extend_from_slice(&chunk[..count]);
                }
                let request: Value = serde_json::from_slice(&bytes[body_start..body_start + content_len]).unwrap();
                if step == 1 {
                    let result = request["messages"].as_array().unwrap().last().unwrap();
                    assert_eq!(result["role"], "tool");
                    assert!(result["content"].as_str().unwrap().starts_with("VERIFY_OK"), "Drift gercek basarili dogrulamadan sonra uretilmeli");
                    fs::write(&target, &changed).unwrap();
                }
                requests.push(request);
                let body = reply.to_string();
                socket.write_all(format!("HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{body}", body.len()).as_bytes()).await.unwrap();
                socket.shutdown().await.unwrap();
            }
            requests
        }).await.expect("Kontrollu drift HTTP testi zaman asimina ugradi")
    });
    (url, server)
}

