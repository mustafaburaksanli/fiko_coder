const WORKSPACE_ONAY_REQUEST: &str = "Modify src/math.rs by adding triple while preserving double, create src/format.rs, and register the format module in src/lib.rs.";
const WORKSPACE_ONAY_LIB: &str = "pub mod math;\n";
const WORKSPACE_ONAY_LIB_UPDATED: &str = "pub mod math;\npub mod format;\n";
const WORKSPACE_ONAY_MATH: &str = "pub fn double(value: i32) -> i32 { value * 2 }\n";
const WORKSPACE_ONAY_MATH_UPDATED: &str = "pub fn double(value: i32) -> i32 { value * 2 }\npub fn triple(value: i32) -> i32 { value * 3 }\n";
const WORKSPACE_ONAY_FORMAT: &str =
    "pub fn label(value: i32) -> String { format!(\"value={value}\") }\n";
const WORKSPACE_ONAY_TEXT: &str =
    "--- src/math.rs\n+++ src/format.rs\nUc dosyanin diff'i hazir. Uygulamak icin ONAYLI yazin.";

fn workspace_onay_project(tag: &str, lib: &str) -> PathBuf {
    let root = mini_crate(tag);
    fs::write(root.join("src/lib.rs"), lib).unwrap();
    fs::write(root.join("src/math.rs"), WORKSPACE_ONAY_MATH).unwrap();
    // Son Cargo cagrisi lock olusturarak rollback fingerprint'ini degistirmesin.
    fs::write(root.join("Cargo.lock"), "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"fiko_mini\"\nversion = \"0.1.0\"\n").unwrap();
    root
}

fn workspace_onay_changes(lib: &str, updated_lib: &str, updated_math: &str) -> Value {
    json!([
        {"operation": "edit", "path": "src/math.rs", "old_text": WORKSPACE_ONAY_MATH, "new_text": updated_math},
        {"operation": "create", "path": "src/format.rs", "content": WORKSPACE_ONAY_FORMAT},
        {"operation": "edit", "path": "src/lib.rs", "old_text": lib, "new_text": updated_lib}
    ])
}

fn workspace_onay_plan() -> Value {
    workspace_onay_changes(
        WORKSPACE_ONAY_LIB,
        WORKSPACE_ONAY_LIB_UPDATED,
        WORKSPACE_ONAY_MATH_UPDATED,
    )
}

fn workspace_onay_tool(name: &str, args: Value) -> Value {
    json!({"message": {"role": "assistant", "tool_calls": [{"function": {"name": name, "arguments": args}}]}})
}

fn workspace_onay_plain() -> Value {
    json!({"message": {"role": "assistant", "content": WORKSPACE_ONAY_TEXT}})
}

async fn workspace_onay_run<P: Prompter>(
    root: &Path,
    replies: Vec<Value>,
    prompter: &mut P,
) -> (Orchestrator, Session, Vec<Value>, Vec<Value>) {
    workspace_onay_run_request(root, WORKSPACE_ONAY_REQUEST, replies, prompter).await
}

async fn workspace_onay_run_request<P: Prompter>(
    root: &Path,
    request: &str,
    replies: Vec<Value>,
    prompter: &mut P,
) -> (Orchestrator, Session, Vec<Value>, Vec<Value>) {
    let (url, server) = mock_ollama(replies).await;
    let mut session = Session::new(root.to_path_buf());
    let mut messages = conversation(request);
    let task = run_task_at(
        &reqwest::Client::builder().no_proxy().build().unwrap(),
        "kontrollu-model",
        &mut session,
        &mut messages,
        prompter,
        &url,
    )
    .await
    .unwrap();
    (task, session, messages, server.await.unwrap())
}

fn workspace_onay_assert_original(root: &Path, lib: &str) {
    assert_eq!(fs::read_to_string(root.join("src/lib.rs")).unwrap(), lib);
    assert_eq!(
        fs::read_to_string(root.join("src/math.rs")).unwrap(),
        WORKSPACE_ONAY_MATH
    );
    assert!(!root.join("src/format.rs").exists());
}

