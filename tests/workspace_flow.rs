//! Cok dosyali araclarin gercek dispatcher, izin, kilit ve rollback akisi.
//! Her Cargo projesi ve target alani teste ait benzersiz temp kokundedir.

use std::collections::{BTreeMap, VecDeque};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{Duration, SystemTime, UNIX_EPOCH};

use fiko_coder::agent::{Prompter, Session, ToolOutcome};
use fiko_coder::execution::TaskPhase;
use fiko_coder::intent::{IntentDecision, TaskIntent, WriteAuthority};
use fiko_coder::orchestrator::{Orchestrator, ProjectState};
use fiko_coder::workspace_patch;
use serde_json::{Value, json};

const LIB: &str = "pub mod extra;\npub fn value() -> u8 { 1 }\n";
const EXTRA: &str = "pub fn extra() -> u8 { 2 }\n";
const MANIFEST: &str =
    "[package]\nname = \"workspace_fixture\"\nversion = \"0.1.0\"\nedition = \"2024\"\n";
const LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"workspace_fixture\"\nversion = \"0.1.0\"\n";
static SEQUENCE: AtomicU64 = AtomicU64::new(0);

struct Project(PathBuf);

impl Project {
    fn new(tag: &str) -> Self {
        let root = std::env::temp_dir().join(format!(
            "fiko_workspace_it_{tag}_{}_{}_{}",
            std::process::id(),
            SEQUENCE.fetch_add(1, Ordering::Relaxed),
            SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        fs::create_dir_all(root.join("src")).unwrap();
        fs::write(root.join("Cargo.toml"), MANIFEST).unwrap();
        fs::write(root.join("Cargo.lock"), LOCK).unwrap();
        fs::write(root.join("src/lib.rs"), LIB).unwrap();
        fs::write(root.join("src/extra.rs"), EXTRA).unwrap();
        fs::write(root.join("keep.txt"), "kullanici dosyasi\n").unwrap();
        Self(root.canonicalize().unwrap())
    }

    fn read(&self, path: &str) -> String {
        fs::read_to_string(self.0.join(path)).unwrap()
    }

    fn snapshot(&self) -> BTreeMap<PathBuf, Vec<u8>> {
        fn visit(root: &Path, directory: &Path, files: &mut BTreeMap<PathBuf, Vec<u8>>) {
            for entry in fs::read_dir(directory).unwrap() {
                let entry = entry.unwrap();
                if ["target", ".fiko_backups"]
                    .contains(&entry.file_name().to_string_lossy().as_ref())
                {
                    continue;
                }
                let path = entry.path();
                if path.is_dir() {
                    visit(root, &path, files);
                } else {
                    files.insert(
                        path.strip_prefix(root).unwrap().to_owned(),
                        fs::read(path).unwrap(),
                    );
                }
            }
        }
        let mut files = BTreeMap::new();
        visit(&self.0, &self.0, &mut files);
        files
    }
}

impl Drop for Project {
    fn drop(&mut self) {
        let temporary_root = std::env::temp_dir().canonicalize().unwrap();
        assert!(self.0.starts_with(temporary_root));
        assert!(
            self.0
                .file_name()
                .unwrap()
                .to_string_lossy()
                .starts_with("fiko_workspace_it_")
        );
        // Windows, bitmis rustc/linker tutamacini kisa sure daha tasiyabilir.
        // Yalniz bu teste ait temp kok icin sinirli tekrar; son hata gizlenmez.
        let mut error = None;
        for delay in [0, 50, 100, 200, 400, 800] {
            if delay > 0 {
                std::thread::sleep(Duration::from_millis(delay));
            }
            match fs::remove_dir_all(&self.0) {
                Ok(()) => return,
                Err(failure) if failure.kind() == io::ErrorKind::NotFound => return,
                Err(failure) => error = Some(failure),
            }
        }
        panic!(
            "Teste ait temp kok temizlenemedi: {:?}: {}",
            self.0,
            error.unwrap()
        );
    }
}

struct Answers {
    answers: VecDeque<bool>,
    asked: Vec<String>,
    change_on_approval: Option<(PathBuf, String)>,
}

impl Answers {
    fn with(answers: &[bool]) -> Self {
        Self {
            answers: answers.iter().copied().collect(),
            asked: Vec::new(),
            change_on_approval: None,
        }
    }

    fn assert_one_patch_approval(&self) {
        assert_eq!(self.asked.len(), 2, "{:?}", self.asked);
        assert!(self.asked[0].contains("cargo check"), "{:?}", self.asked);
        assert!(self.asked[1].contains("Tum workspace"), "{:?}", self.asked);
    }
}

impl Prompter for Answers {
    fn ask_yes(&mut self, question: &str) -> io::Result<bool> {
        self.asked.push(question.into());
        if question.contains("Tum workspace")
            && let Some((path, content)) = self.change_on_approval.take()
        {
            fs::write(path, content)?;
        }
        Ok(self.answers.pop_front().unwrap_or(false))
    }
}

fn modify_task() -> Orchestrator {
    modify_task_for("Update src/lib.rs and src/extra.rs in the project.")
}

fn modify_task_for(request: &str) -> Orchestrator {
    let task = Orchestrator::for_request(request);
    assert_eq!(task.intent(), TaskIntent::Modify);
    assert_eq!(task.authority(), WriteAuthority::Granted);
    task
}

fn edit(path: &str, old: &str, new: &str) -> Value {
    json!({"operation": "edit", "path": path, "old_text": old, "new_text": new})
}

fn create(path: &str, content: &str) -> Value {
    json!({"operation": "create", "path": path, "content": content})
}

fn two_edits() -> Value {
    json!({"changes": [
        edit("src/lib.rs", "pub fn value() -> u8 { 1 }", "pub fn value() -> u8 { 3 }"),
        edit("src/extra.rs", "pub fn extra() -> u8 { 2 }", "pub fn extra() -> u8 { 4 }")
    ]})
}

async fn dispatch(
    task: &mut Orchestrator,
    session: &mut Session,
    answers: &mut Answers,
    name: &str,
    args: &Value,
) -> ToolOutcome {
    task.execute(session, answers, name, args).await.unwrap()
}

fn assert_applied(task: &Orchestrator, session: &Session, outcome: &ToolOutcome) {
    assert!(
        outcome.output.starts_with("PATCH_VERIFIED"),
        "{}",
        outcome.output
    );
    assert!(outcome.stop.is_some());
    assert!(
        outcome.output.contains("Cikis kodu: 0"),
        "{}",
        outcome.output
    );
    assert_eq!(task.project_state(), ProjectState::VerifiedPatch);
    assert_eq!(task.phase(), TaskPhase::Completed);
    assert!(task.applied());
    assert_eq!(task.repair.verify_attempts(), 1);
    assert_eq!(task.repair.approved_attempts(), 1);
    assert!(session.last_workspace.is_some());
    assert!(session.last_patch.is_none());
}

#[tokio::test]
async fn iki_mevcut_dosya_tek_onayla_birlikte_dogrulanip_uygulanmali() {
    let project = Project::new("two_edits");
    let mut task = modify_task();
    let mut session = Session::new(project.0.clone());
    let mut answers = Answers::with(&[true, true]);
    let args = two_edits();
    let verified = dispatch(
        &mut task,
        &mut session,
        &mut answers,
        "verify_workspace",
        &args,
    )
    .await;
    assert!(
        verified.output.starts_with("VERIFY_OK"),
        "{}",
        verified.output
    );
    assert_eq!(project.read("src/lib.rs"), LIB);
    assert_eq!(project.read("src/extra.rs"), EXTRA);
    assert!(!project.0.join(".fiko_backups").exists());
    assert!(!task.applied());
    let outcome = dispatch(
        &mut task,
        &mut session,
        &mut answers,
        "apply_workspace",
        &args,
    )
    .await;
    assert_applied(&task, &session, &outcome);
    answers.assert_one_patch_approval();
    assert_eq!(project.read("src/lib.rs"), LIB.replace("{ 1 }", "{ 3 }"));
    assert_eq!(
        project.read("src/extra.rs"),
        EXTRA.replace("{ 2 }", "{ 4 }")
    );
    assert_eq!(session.last_workspace.as_ref().unwrap().files.len(), 2);
}

